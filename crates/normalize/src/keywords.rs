pub fn is_reserved(word: &str) -> bool {
    // 대문자 변환을 스택 버퍼로 처리해 할당을 피한다. 예약어는 모두 ASCII 30자 미만이다.
    let mut buf = [0u8; 32];
    let bytes = word.as_bytes();
    if bytes.len() > buf.len() || !word.is_ascii() {
        return false;
    }
    for (i, b) in bytes.iter().enumerate() {
        buf[i] = b.to_ascii_uppercase();
    }
    let upper = std::str::from_utf8(&buf[..bytes.len()]).unwrap_or("");
    RESERVED.binary_search(&upper).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_invariant() {
        // 이진 탐색이 정렬을 전제한다. 항목 추가 시 이 테스트가 실수를 잡는다.
        for w in RESERVED.windows(2) {
            assert!(w[0] < w[1], "정렬 위반: {:?} 뒤에 {:?}", w[0], w[1]);
        }
    }

    #[test]
    fn recognizes_reserved_case_insensitively() {
        for w in [
            "select",
            "SELECT",
            "Select",
            "order",
            "values",
            "in",
            "intersect",
        ] {
            assert!(is_reserved(w), "{w} 는 예약어여야 한다");
        }
    }

    #[test]
    fn rejects_non_reserved() {
        // 이 단어들이 들어가면 수렴성이 깨진다 (모듈 문서의 "과잉" 행).
        for w in [
            "status",
            "date",
            "timestamp",
            "datetime",
            "count",
            "data",
            "type",
            "value",
            "text",
            "user",
            "source",
            "start",
            "end",
            "level",
            "name",
            "comment",
            "enum",
            "any",
            "some",
            "local",
            "global",
            "session",
            "first",
            "last",
            "next",
        ] {
            assert!(!is_reserved(w), "{w} 는 비예약어라 제외해야 한다");
        }
    }

    #[test]
    fn handles_oversized_and_non_ascii_input() {
        assert!(!is_reserved(&"x".repeat(64)));
        assert!(!is_reserved("주문"));
    }
}
