//! MySQL **예약어**(reserved word) 집합.
//!
//! # 왜 예약어만 넣는가 — 오류 방향이 비대칭이다
//!
//! `fold_ident` 가 비예약어를 소문자로 접으므로, 이 집합의 오류는 한쪽만 위험하다.
//!
//! | 실수 | 예 | 원문 | `DIGEST_TEXT` | 결과 |
//! |---|---|---|---|---|
//! | **누락** (예약어를 빼먹음) | `LATERAL` 없음 | `lateral` → `lateral` | `LATERAL` → `lateral` | **수렴한다.** 무해 |
//! | **과잉** (비예약어를 넣음) | `STATUS` 추가 | `status` → `STATUS` | `` `status` `` → `status` | **갈라진다.** 그룹핑 붕괴 |
//!
//! 그래서 확신하는 것만 넣는다. 비예약어(`STATUS`, `DATE`, `TIMESTAMP`, `COUNT`, `DATA`,
//! `TYPE`, `VALUE`, `TEXT`, `USER`, `SOURCE`, `START`, `END`, `LEVEL`, `NAME` 등)는
//! **절대 넣지 않는다** — 인용 없이 컬럼명으로 쓸 수 있는 단어들이다.
//!
//! 목록은 MySQL 8.0 / 8.4 의 예약어를 기준으로 한다([ADR-019](../../../docs/03-decisions.md)
//! 의 버전 하한). `INTERSECT`·`EXCEPT`(8.0.31+), `ARRAY`·`MEMBER`(8.0.17+),
//! `SOURCE_BIND`(8.4) 를 포함한다.
//!
//! `MASTER_*` / `SOURCE_*` 는 MySQL 문법 토큰을 그대로 인용한 것이며 우리가 고른 이름이 아니다.

